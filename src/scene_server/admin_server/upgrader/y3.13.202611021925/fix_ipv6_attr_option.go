// fixIPv6AttrOption replaces the ipv6 option of the host ipv6 attributes with the correct one, so that a comma
// separated ipv6 list can be matched. Only the host ipv6 attributes are replaced: the process bind_info ip holds a
// single ipv6 value, so it keeps its own option.
func fixIPv6AttrOption(ctx context.Context, db dal.RDB) error {
	filter := map[string]interface{}{
		common.BKObjIDField: common.BKInnerObjIDHost,
		common.BKPropertyIDField: map[string]interface{}{
			common.BKDBIN: []string{common.BKHostInnerIPv6Field, common.BKHostOuterIPv6Field},
		},
	}
	updateDoc := map[string]interface{}{common.BKOptionField: hostIPv6Regex}

	if _, err := db.Table(common.BKTableNameObjAttDes).UpdateMany(ctx, filter, updateDoc); err != nil {
		blog.Errorf("update host ipv6 option failed, filter: %v, err: %v", filter, err)
		return err
	}

	blog.Infof("fix host ipv6 option success, filter: %v", filter)
	return nil
}
